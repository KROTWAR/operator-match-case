rate = int(input("Рейтинг (1-10)"))

match rate:
    case 9 | 10:
        print(f"Рейтинг {rate} - Отличный продукт! Настоятельно рекомендую!")
    case 7 | 8:
        print(f"Рейтинг {rate} - Хороший продукт. Рекомендую!")
    case 4 | 5 | 6:
        print(f"Рейтинг {rate} - Средний продукт. Можно попробовать")
    case 1 | 2 | 3:
        print(f"Рейтинг {rate} - Плохой продукт. Не рекомендую")
    case _:
        print("Ошибка: Введите от 1 до 10")
