import random

status = input("Введите статус заказа (pending, processing, shipped, delivered, cancelled): ").strip().lower()

match status:
    case "pending":
        days = random.randint(1, 2)
        print("╔════════════════════════════════════╗")
        print("║     📦 СТАТУС ВАШЕГО ЗАКАЗА 📦     ║")
        print("╚════════════════════════════════════╝")
        print("Статус: В ожидании")
        print("Описание: Заказ создан и ожидает подтверждения")
        print(f"Примерное время: {days} дн.")
        print("Рекомендация: Ожидайте начала обработки")

    case "processing":
        days = random.randint(1, 3)
        print("╔════════════════════════════════════╗")
        print("║     📦 СТАТУС ВАШЕГО ЗАКАЗА 📦     ║")
        print("╚════════════════════════════════════╝")
        print("Статус: В обработке ")
        print("Описание: Ваш заказ собирается и упаковывается на складе")
        print(f"Примерное время: {days} дн.")
        print("Рекомендация: Скоро заказ будет передан в доставку")

    case "shipped":
        days = random.randint(2, 5)
        print("╔════════════════════════════════════╗")
        print("║     📦 СТАТУС ВАШЕГО ЗАКАЗА 📦     ║")
        print("╚════════════════════════════════════╝")
        print("Статус: Отправлено ")
        print("Описание: Ваш заказ находится в пути к вам")
        print(f"Примерное время: {days} дн.")
        print("Рекомендация: Следите за уведомлениями о доставке")

    case "delivered":
        print("╔════════════════════════════════════╗")
        print("║     📦 СТАТУС ВАШЕГО ЗАКАЗА 📦     ║")
        print("╚════════════════════════════════════╝")
        print("Статус: Доставлено ")
        print("Описание: Заказ успешно вручен получателю")
        print("Примерное время: 0 дн. (завершено)")
        print("Рекомендация: Будем рады вашему отзыву!")

    case "cancelled":
        print("╔════════════════════════════════════╗")
        print("║     📦 СТАТУС ВАШЕГО ЗАКАЗА 📦     ║")
        print("╚════════════════════════════════════╝")
        print("Статус: Отменено")
        print("Описание: Заказ был отменен")
        print("Примерное время: —")
        print("Рекомендация: Оформите новый заказ при необходимости")

    case _:
        print(f' Ошибка: Неизвестный статус "{status}"')
        print("Доступные статусы: pending, processing, shipped, delivered, cancelled")